// Concatenates all migrations + the starter catalog into supabase/setup.sql,
// for a one-paste setup in the Supabase SQL Editor. Run: npm run db:setup-sql
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = 'supabase/migrations';
const parts = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort().map((f) => `-- >>> ${f}\n${readFileSync(`${dir}/${f}`, 'utf8')}`);
parts.push(`-- >>> seed_catalog.sql\n${readFileSync('supabase/seed_catalog.sql', 'utf8')}`);
writeFileSync(
  'supabase/setup.sql',
  `-- MAX — one-shot database setup (generated by scripts/build-setup-sql.mjs; do not edit by hand).\n` +
    `-- Paste into Supabase → SQL Editor → Run, on an EMPTY project.\n\n` +
    parts.join('\n\n'),
);
console.log('supabase/setup.sql written');
